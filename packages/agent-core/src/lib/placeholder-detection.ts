/**
 * Shared placeholder / scaffolding-artifact detectors used by BOTH the
 * orchestrator's end-of-turn suppression and the `sendMessageToUser`
 * tool's delivery filter. Keeping a single source of truth ensures the
 * two delivery paths cannot drift: whatever is suppressed on one path
 * is also suppressed on the other.
 *
 * Narrow on purpose: real short replies like "ok" / "done" / "4" must
 * still reach the user because the default agent prompt invites the
 * model to write a concise completion summary as end-of-turn text.
 *
 * The module is side-effect-free, has no IO, and does not depend on any
 * AWS SDK, so it can be imported from any package in the monorepo.
 */

/**
 * Trim-and-classify helper for the placeholder detector.
 *
 * Suppressed patterns (after stripping invisible unicode + trimming):
 * - undefined / null
 * - empty string / whitespace-only
 * - one-to-three dots (".", "..", "...")
 * - single non-letter/non-digit character (e.g. ",", ";", "_")
 *
 * Invisible unicode stripped before the trim: zero-width space (U+200B),
 * zero-width non-joiner (U+200C), zero-width joiner (U+200D), word joiner
 * (U+2060), and BOM / zero-width no-break space (U+FEFF). These code
 * points are NOT whitespace from `String.prototype.trim`'s perspective,
 * so without the explicit strip a stream like `"\u200B."` would survive
 * as a non-placeholder and get delivered to Slack as a visible ".".
 * Real-world LLM streams occasionally inject these at chunk boundaries.
 */
export const isEndOfTurnPlaceholder = (text: string | undefined | null): boolean => {
  if (text == null) return true;
  const stripped = text.replace(/[\u200B-\u200D\u2060\uFEFF]/g, '');
  const trimmed = stripped.trim();
  if (trimmed.length === 0) return true;
  if (trimmed === '.' || trimmed === '..' || trimmed === '...') return true;
  if (trimmed.length === 1 && /^[^\p{L}\p{N}]$/u.test(trimmed)) return true;
  return false;
};

/**
 * Scaffolding-artifact detector. Matches texts whose ENTIRE content is a
 * single `<...>` block — e.g. `"<continued in the following tool call>"`
 * (or its non-English equivalent) emitted alone as a placeholder. These are
 * LLM scaffolding artifacts with no user-facing value.
 *
 * Narrow conditions to avoid false positives against legitimate messages
 * that happen to *contain* tag-shaped text:
 *   - whole message is a single `<...>` block (anchored ^ and $)
 *   - inner content has no `<`, `>`, or newline (so nested / multi-line
 *     markup is never matched as a whole)
 *   - inner length 1–100
 *
 * Unlike `stripScaffoldingPrefix`, no keyword gate is needed: if the
 * ENTIRE message is a single short `<...>` block, user-facing value is
 * zero regardless of the inner text — real replies never take that shape.
 */
const SCAFFOLDING_ARTIFACT_RE = /^<[^<>\n]{1,100}>$/;
export const isScaffoldingArtifact = (text: string | undefined | null): boolean => {
  if (text == null) return false;
  const stripped = text.replace(/[\u200B-\u200D\u2060\uFEFF]/g, '').trim();
  return SCAFFOLDING_ARTIFACT_RE.test(stripped);
};

/**
 * Strip a leading scaffolding-style `<...>` block from `text`, but ONLY
 * when the inner content contains a scaffolding keyword (not real
 * markup). Real HTML tags (`<div>`, `<html>`, `<strong>`, `<?xml ...?>`)
 * have no scaffolding keyword in the inner text and are passed through
 * untouched. If a future artifact uses a keyword that is not yet listed
 * the message is still delivered, which is the safer failure mode.
 *
 * The returned string has any leading whitespace trimmed (but not
 * trailing), since the scaffolding block itself is the decorator.
 */
const SCAFFOLDING_PREFIX_RE = /^<([^<>\n]{1,100})>/;
// Keyword gate for the prefix stripper. Includes non-ASCII (e.g. Japanese)
// markers as FUNCTIONAL literals: the inference backend emits scaffolding tags
// in the agent's working language, so these must be matched, not treated as
// example text. Japanese: 続き=continued, 以下=below/following, 呼び出し=call.
const SCAFFOLDING_KEYWORDS = /続き|continue|以下|next|tool|呼び出し|call|step|below/i;
export const stripScaffoldingPrefix = (text: string): string => {
  const m = SCAFFOLDING_PREFIX_RE.exec(text);
  if (!m) return text;
  const inner = m[1]!;
  if (!SCAFFOLDING_KEYWORDS.test(inner)) return text;
  return text.slice(m[0].length).replace(/^\s+/, '');
};

/**
 * Detect known interrupt / cancellation placeholder texts emitted by
 * the inference backend when a `session/cancel` is processed. These are boilerplate
 * responses generated by the inference backend (not the model) and carry
 * no user-facing value — they confuse the user because the *agent*
 * initiated the cancel, not the user.
 *
 * The regex is intentionally anchored and case-insensitive to tolerate
 * minor punctuation / capitalisation variance across backend versions,
 * while remaining narrow enough to never match a real model reply.
 */
const INTERRUPT_PLACEHOLDER_RE = /^response was interrupted by the user\.?$/i;
export const isInterruptPlaceholder = (text: string | undefined | null): boolean => {
  if (text == null) return false;
  const stripped = text.replace(/[\u200B-\u200D\u2060\uFEFF]/g, '').trim();
  return INTERRUPT_PLACEHOLDER_RE.test(stripped);
};

/**
 * Detect single-word acknowledgement responses that a backend's protocol may
 * inject as synthetic assistant messages to satisfy alternating-turn
 * requirements. When the model echoes these on an agentMessage-triggered turn,
 * they carry no user-facing value and should be suppressed.
 */
const ACK_WORD_PLACEHOLDER_RE = /^(understood|noted|acknowledged|ok|got it|roger|copy)\.?$/i;
export const isAckWordPlaceholder = (text: string | undefined | null): boolean => {
  if (text == null) return false;
  const stripped = text.replace(/[\u200B-\u200D\u2060\uFEFF]/g, '').trim();
  return ACK_WORD_PLACEHOLDER_RE.test(stripped);
};

/**
 * One-shot sanitize + placeholder check for delivery-path filters.
 *
 * Returns `{ shouldSend: false }` when the caller must NOT forward the
 * message to the user: either the whole message is a scaffolding
 * artifact, OR after stripping a scaffolding prefix the remainder is a
 * placeholder. Returns `{ shouldSend: true, message }` with the stripped
 * body otherwise, so callers deliver the user-visible remainder rather
 * than the raw text with its decorator.
 */
export const sanitiseForDelivery = (text: string): { shouldSend: true; message: string } | { shouldSend: false } => {
  if (isScaffoldingArtifact(text)) return { shouldSend: false };
  if (isInterruptPlaceholder(text)) return { shouldSend: false };
  const stripped = stripScaffoldingPrefix(text);
  if (isEndOfTurnPlaceholder(stripped)) return { shouldSend: false };
  return { shouldSend: true, message: stripped };
};
